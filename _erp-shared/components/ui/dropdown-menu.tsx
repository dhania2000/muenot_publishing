/**
 * Base UI menu items only emit `onClick`; the Radix/shadcn API that most of
 * the codebase was written against is `onSelect`. Bridge the two so either
 * prop works: `onSelect` runs on activation (click or Enter/Space, which Base
 * UI dispatches as a click), followed by any explicit `onClick`.
 */
type SelectBridgeProps = {
  onSelect?: (event: Event) => void
  onClick?: React.MouseEventHandler<HTMLDivElement>
}

function bridgeOnSelect<T extends SelectBridgeProps>({ onSelect, onClick, ...rest }: T) {
  if (!onSelect) return { onClick, ...rest }
  const handleClick: React.MouseEventHandler<HTMLDivElement> = (event) => {
    onSelect(event.nativeEvent)
    onClick?.(event)
  }
  return { onClick: handleClick, ...rest }
}

